// Integration tests for pnpm eval. T13 and T14 drive a running replay stack, so they run only when EVAL_BASE_URL names one: scripts/check-wave-2.sh
// sets it to the api and worker of its row 09. A plain vitest run has no api or worker, and CI starts none. T15 always runs.
import { execSync, spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

const PACKAGE_DIR = join(import.meta.dirname, "..");
const LABELS = ["evidence validity", "grounded brief rate", "support rate", "injection leakage", "end-to-end completion by fresh pairs", "first-turn latency", "cost per complete pair"];

// True when a running replay stack is named: the api base and the worker database.
const hasStack = process.env.EVAL_BASE_URL !== undefined && process.env.DATABASE_URL_WORKER !== undefined;

// Runs the eval command with the arguments, from the package folder, and returns its exit code and output.
function runEval(args: string[]): { status: number | null; stdout: string; stderr: string } {
  const result = spawnSync("pnpm", ["exec", "tsx", "src/run-eval.ts", ...args], { cwd: PACKAGE_DIR, encoding: "utf8", env: process.env });
  return { status: result.status, stdout: result.stdout, stderr: result.stderr };
}

describe.runIf(hasStack)("run-eval against the replay stack", () => {
  it("W2-EVAL-T13 (A2): pnpm eval --replay prints the seven metrics with sample sizes and writes eval/results.json with the commit hash and date", () => {
    const folder = mkdtempSync(join(tmpdir(), "eval-run-"));
    const resultsPath = join(folder, "results.json");
    const run = runEval(["--replay", "--pairs", "fixtures/pairs.replay.json", "--results", resultsPath]);
    for (const label of LABELS) expect(run.stdout).toContain(label);
    expect(run.stdout).toMatch(/Generated by pnpm eval at .+ from commit [0-9a-f]{7}, LLM_MODE replay, model /);
    const saved = JSON.parse(readFileSync(resultsPath, "utf8")) as { commit: string; date: string; metrics: Array<{ n: number }> };
    expect(saved.commit).toBe(execSync("git rev-parse HEAD", { cwd: PACKAGE_DIR, encoding: "utf8" }).trim());
    expect(Number.isNaN(Date.parse(saved.date))).toBe(false);
    expect(saved.metrics).toHaveLength(7);
    for (const metric of saved.metrics) expect(metric.n).toBeGreaterThanOrEqual(0);
  });

  it("W2-EVAL-T14 (A2): the process exits non-zero when a threshold fails, using a targets file with grounded_brief_rate 1.01 (a fake target)", () => {
    const folder = mkdtempSync(join(tmpdir(), "eval-threshold-"));
    const targetsPath = join(folder, "targets.json");
    const targets = JSON.parse(readFileSync(join(PACKAGE_DIR, "fixtures", "expected", "targets.json"), "utf8")) as Record<string, number | null>;
    targets.grounded_brief_rate = 1.01;
    writeFileSync(targetsPath, JSON.stringify(targets));
    const run = runEval(["--replay", "--pairs", "fixtures/pairs.replay.json", "--results", join(folder, "results.json"), "--targets", targetsPath]);
    expect(run.status).toBe(1);
    expect(run.stdout).toContain("grounded_brief_rate");
  });

});

describe("run-eval source", () => {
  it("W2-EVAL-T15 (invariant 15): collectRows reads nothing outside withMeeting and withPerson (static check, by reading the source)", () => {
    const source = readFileSync(join(PACKAGE_DIR, "src", "collect-rows.ts"), "utf8");
    expect(source).not.toContain("db.selectFrom");
    expect(source).not.toContain("db.selectNoFrom");
    expect(source).toContain("withMeeting(");
    expect(source).toContain("withPerson(");
  });
});
