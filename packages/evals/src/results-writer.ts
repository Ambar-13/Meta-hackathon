// The results of one run: the table printed to stdout, the results file, the README block and the exit code.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { EvalFailure } from "./eval-flags.js";
import type { MetricKey, MetricResult } from "./metrics/index.js";

// Everything one run writes: the commit and time, the mode and model, the pairs, the metrics and the planted-secret count.
export type EvalResults = {
  commit: string;
  date: string;
  llmMode: "replay" | "live";
  model: string;
  baseUrl: string;
  pairsRun: number;
  pairErrors: { pair: string; code: string }[];
  metrics: MetricResult[];
  thresholdFailures: MetricKey[];
  scrubPlantedSurvivors: number | null;
  scrubPlantedTotal: number | null;
};

// The two metrics that gate the exit code: grounding has a floor, and leakage has a ceiling.
const THRESHOLD_KEYS: readonly MetricKey[] = ["grounded_brief_rate", "injection_leakage"];
// The words that follow the sample size of each metric in the table.
const SAMPLE_WORDS: Record<MetricKey, string> = {
  evidence_validity: "claims",
  grounded_brief_rate: "lines",
  support_rate: "reliable briefs",
  injection_leakage: "markers",
  completion_rate: "meetings started",
  first_turn_latency_ms: "meetings with a value",
  cost_per_complete_pair_usd: "completed meetings",
};
// The start marker and end marker of the generated eval block in the root README.
const EVAL_START = "<!-- eval:start -->";
const EVAL_END = "<!-- eval:end -->";
// The start marker and end marker of the human block in the root README.
const HUMAN_START = "<!-- human-metrics:start -->";
const HUMAN_END = "<!-- human-metrics:end -->";

// Whether one metric is past its threshold: below a floor, or above a ceiling.
function isFailing(metric: MetricResult): boolean {
  if (metric.value === null || metric.target === null) return false;
  if (metric.direction === "at_least") return metric.value < metric.target;
  if (metric.direction === "at_most") return metric.value > metric.target;
  return false;
}

// The keys of the metrics past their threshold, in table order.
export function thresholdFailuresOf(metrics: readonly MetricResult[]): MetricKey[] {
  return metrics.filter(isFailing).map((metric) => metric.key);
}

// One line per failed threshold, naming the metric, its value and its target, for the console.
export function thresholdLinesOf(results: EvalResults): string[] {
  return results.metrics
    .filter(isFailing)
    .map(
      (metric) =>
        `Threshold failed: ${metric.key} is ${metric.display}; target ${metric.direction === "at_least" ? "at or above" : "at or below"} ${String(metric.target)}.`,
    );
}

// The target column text: the threshold in words, or print only when the metric has none.
function targetText(metric: MetricResult): string {
  if (metric.target === null || metric.direction === null) return "print only";
  return `${metric.direction === "at_least" ? "at or above" : "at or below"} ${String(metric.target)}`;
}

// One row of the table for one metric.
function rowLine(metric: MetricResult): string {
  return `| ${metric.label} | ${metric.display} | ${String(metric.n)} ${SAMPLE_WORDS[metric.key]} | ${targetText(metric)} | ${metric.rows.join(", ")} |`;
}

// The table of the seven metrics, then the planted-secret line when the count ran. It is the same text the README block holds.
export function formatResultsTable(results: EvalResults): string {
  const lines = [
    "| Metric | Value | n | Target | Rows |",
    "|---|---|---|---|---|",
    ...results.metrics.map(rowLine),
  ];
  if (results.scrubPlantedSurvivors !== null && results.scrubPlantedTotal !== null) {
    lines.push(
      `Planted secrets surviving the scrub: ${String(results.scrubPlantedSurvivors)} of ${String(results.scrubPlantedTotal)}`,
    );
  }
  return lines.join("\n");
}

// The last line of the table: when and from which commit the numbers came, in which mode and with which model.
export function generatedByLine(results: EvalResults): string {
  return `Generated by pnpm eval at ${results.date} from commit ${results.commit.slice(0, 7)}, LLM_MODE ${results.llmMode}, model ${results.model}.`;
}

// Exit code 1 only when grounding is under its floor or leakage is over its ceiling. A null value never fails the run.
export function decideExitCode(results: EvalResults): 0 | 1 {
  return thresholdFailuresOf(results.metrics).some((key) => THRESHOLD_KEYS.includes(key)) ? 1 : 0;
}

// Writes eval/results.json as pretty JSON with a trailing newline, and creates its folder.
export async function writeResultsFile(results: EvalResults, path: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, `${JSON.stringify(results, null, 2)}\n`);
}

// Replaces the text between a start marker and an end marker with the block. A missing marker is refused with its name.
function replaceBlock(
  text: string,
  markers: { start: string; end: string },
  block: string,
): string {
  const startAt = text.indexOf(markers.start);
  const endAt = text.indexOf(markers.end, startAt + markers.start.length);
  if (startAt === -1 || endAt === -1)
    throw new EvalFailure(
      "readme_markers_missing",
      `The README has no ${markers.start} and ${markers.end} pair. Add the markers under the Eval table heading.`,
    );
  return `${text.slice(0, startAt + markers.start.length)}\n${block}${text.slice(endAt)}`;
}

// Writes the eval block and, when a human table is given, the human block into the README. Nothing outside the markers changes.
export async function writeReadmeBlock(
  readmePath: string,
  results: EvalResults,
  humanTable: string | null,
): Promise<void> {
  const original = await readFile(readmePath, "utf8").catch(() => {
    throw new EvalFailure(
      "readme_missing",
      `No README at ${readmePath}. Add it with the eval markers, then run pnpm eval --write-readme again.`,
    );
  });
  let text = replaceBlock(
    original,
    { start: EVAL_START, end: EVAL_END },
    `${formatResultsTable(results)}\n${generatedByLine(results)}\n`,
  );
  if (humanTable !== null)
    text = replaceBlock(text, { start: HUMAN_START, end: HUMAN_END }, `${humanTable}\n`);
  await writeFile(readmePath, text);
}
